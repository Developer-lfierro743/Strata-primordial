/* Forward decl: the inline capture below writes the BMP; strata_write_bmp is
 * defined after this function. */
static inline void strata_write_bmp(const char *path, const uint8_t *pixels, uint32_t w, uint32_t h);

static inline uint32_t strata_swapchain_needs_rebuild(void *swapchain) {
    StrataSwapchain *sc = (StrataSwapchain *)swapchain;
    if (sc->needsRebuild) {
        sc->needsRebuild = 0;
        return 1;
    }
    return 0;
}

static inline void strata_render_frame(void *instance, void *physDevice, void *device, void *queue,
                                        StrataSwapchain *sc, StrataPipeline *pl,
                                        const float *worldPC,
                                        StrataPipeline *water,
                                        StrataPipeline *hud,
                                        const float *hudPC,
                                        const uint32_t *ranges, uint32_t rangeCount) {
    /* worldPC: 20 floats = MVP(16) + camPos(3) + time(1).
       hudPC:   16 floats = HUD MVP (vertices are already in clip space).
       ranges:  per-chunk draw list, 4 uint32s per chunk =
                (solidFirstVertex, solidVertexCount, waterFirstVertex, waterVertexCount).
                The Kotlin side frustum-culls chunks before building this, so
                off-screen chunks are skipped at draw time. */
    if (!sc) return;
    PFN_vkGetInstanceProcAddr vkGetProcAddr = (PFN_vkGetInstanceProcAddr)SDL_Vulkan_GetVkGetInstanceProcAddr();
    PFN_vkAcquireNextImageKHR vkAcquireNextImageFn = (PFN_vkAcquireNextImageKHR)vkGetProcAddr((VkInstance)instance, "vkAcquireNextImageKHR");
    PFN_vkResetCommandBuffer vkResetCommandBufferFn = (PFN_vkResetCommandBuffer)vkGetProcAddr((VkInstance)instance, "vkResetCommandBuffer");
    PFN_vkBeginCommandBuffer vkBeginCommandBufferFn = (PFN_vkBeginCommandBuffer)vkGetProcAddr((VkInstance)instance, "vkBeginCommandBuffer");
    PFN_vkCmdBeginRenderPass vkCmdBeginRenderPassFn = (PFN_vkCmdBeginRenderPass)vkGetProcAddr((VkInstance)instance, "vkCmdBeginRenderPass");
    PFN_vkCmdBindPipeline vkCmdBindPipelineFn = (PFN_vkCmdBindPipeline)vkGetProcAddr((VkInstance)instance, "vkCmdBindPipeline");
    PFN_vkCmdSetViewport vkCmdSetViewportFn = (PFN_vkCmdSetViewport)vkGetProcAddr((VkInstance)instance, "vkCmdSetViewport");
    PFN_vkCmdSetScissor vkCmdSetScissorFn = (PFN_vkCmdSetScissor)vkGetProcAddr((VkInstance)instance, "vkCmdSetScissor");
    PFN_vkCmdBindVertexBuffers vkCmdBindVertexBuffersFn = (PFN_vkCmdBindVertexBuffers)vkGetProcAddr((VkInstance)instance, "vkCmdBindVertexBuffers");
    PFN_vkCmdPushConstants vkCmdPushConstantsFn = (PFN_vkCmdPushConstants)vkGetProcAddr((VkInstance)instance, "vkCmdPushConstants");
    PFN_vkCmdDraw vkCmdDrawFn = (PFN_vkCmdDraw)vkGetProcAddr((VkInstance)instance, "vkCmdDraw");
    PFN_vkCmdEndRenderPass vkCmdEndRenderPassFn = (PFN_vkCmdEndRenderPass)vkGetProcAddr((VkInstance)instance, "vkCmdEndRenderPass");
    PFN_vkEndCommandBuffer vkEndCommandBufferFn = (PFN_vkEndCommandBuffer)vkGetProcAddr((VkInstance)instance, "vkEndCommandBuffer");
    PFN_vkQueueSubmit vkQueueSubmitFn = (PFN_vkQueueSubmit)vkGetProcAddr((VkInstance)instance, "vkQueueSubmit");
    PFN_vkQueuePresentKHR vkQueuePresentFn = (PFN_vkQueuePresentKHR)vkGetProcAddr((VkInstance)instance, "vkQueuePresentKHR");
    PFN_vkWaitForFences vkWaitForFencesFn = (PFN_vkWaitForFences)vkGetProcAddr((VkInstance)instance, "vkWaitForFences");
    PFN_vkResetFences vkResetFencesFn = (PFN_vkResetFences)vkGetProcAddr((VkInstance)instance, "vkResetFences");
    PFN_vkCmdPipelineBarrier vkCmdPipelineBarrierFn = (PFN_vkCmdPipelineBarrier)vkGetProcAddr((VkInstance)instance, "vkCmdPipelineBarrier");
    PFN_vkCmdCopyImageToBuffer vkCmdCopyImageToBufferFn = (PFN_vkCmdCopyImageToBuffer)vkGetProcAddr((VkInstance)instance, "vkCmdCopyImageToBuffer");
    PFN_vkQueueWaitIdle vkQueueWaitIdleFn = (PFN_vkQueueWaitIdle)vkGetProcAddr((VkInstance)instance, "vkQueueWaitIdle");
    PFN_vkCreateBuffer vkCreateBufferFn = (PFN_vkCreateBuffer)vkGetProcAddr((VkInstance)instance, "vkCreateBuffer");
    PFN_vkGetBufferMemoryRequirements vkGetBufferMemoryRequirementsFn = (PFN_vkGetBufferMemoryRequirements)vkGetProcAddr((VkInstance)instance, "vkGetBufferMemoryRequirements");
    PFN_vkAllocateMemory vkAllocateMemoryFn = (PFN_vkAllocateMemory)vkGetProcAddr((VkInstance)instance, "vkAllocateMemory");
    PFN_vkBindBufferMemory vkBindBufferMemoryFn = (PFN_vkBindBufferMemory)vkGetProcAddr((VkInstance)instance, "vkBindBufferMemory");
    PFN_vkMapMemory vkMapMemoryFn = (PFN_vkMapMemory)vkGetProcAddr((VkInstance)instance, "vkMapMemory");
    PFN_vkUnmapMemory vkUnmapMemoryFn = (PFN_vkUnmapMemory)vkGetProcAddr((VkInstance)instance, "vkUnmapMemory");
    PFN_vkDestroyBuffer vkDestroyBufferFn = (PFN_vkDestroyBuffer)vkGetProcAddr((VkInstance)instance, "vkDestroyBuffer");
    PFN_vkFreeMemory vkFreeMemoryFn = (PFN_vkFreeMemory)vkGetProcAddr((VkInstance)instance, "vkFreeMemory");

    if (!vkAcquireNextImageFn || !vkResetCommandBufferFn || !vkBeginCommandBufferFn ||
        !vkCmdBeginRenderPassFn || !vkCmdBindPipelineFn || !vkCmdSetViewportFn || !vkCmdSetScissorFn ||
        !vkCmdBindVertexBuffersFn || !vkCmdPushConstantsFn || !vkCmdDrawFn ||
        !vkCmdEndRenderPassFn || !vkEndCommandBufferFn || !vkQueueSubmitFn || !vkQueuePresentFn ||
        !vkWaitForFencesFn || !vkResetFencesFn || !vkCmdPipelineBarrierFn || !vkCmdCopyImageToBufferFn ||
        !vkQueueWaitIdleFn || !vkCreateBufferFn || !vkGetBufferMemoryRequirementsFn || !vkAllocateMemoryFn ||
        !vkBindBufferMemoryFn || !vkMapMemoryFn || !vkUnmapMemoryFn || !vkDestroyBufferFn || !vkFreeMemoryFn) {
        fprintf(stderr, "strata_render_frame: failed to load required Vulkan functions\n");
        return;
    }

    /* Ring cursor: each frame uses its own semaphore pair so a signal is
     * never re-issued while still pending (see StrataSwapchain comment). */
    const uint32_t ring = sc->frameIndex % 3;

    uint32_t imageIndex = 0;
    VkResult acquireResult = vkAcquireNextImageFn((VkDevice)device, sc->swapchain, UINT64_MAX, sc->imageAvailableSemaphores[ring], VK_NULL_HANDLE, &imageIndex);
    if (acquireResult == VK_ERROR_OUT_OF_DATE_KHR || acquireResult == VK_SUBOPTIMAL_KHR) {
        sc->needsRebuild = 1;
        return;
    }
    if (acquireResult != VK_SUCCESS) {
        /* VK_ERROR_DEVICE_LOST (-4) is fatal — trigger rebuild to stop the
         * tight retry loop; the rebuild will likely fail too, but at least
         * we exit the spiral gracefully instead of spinning forever. */
        if (acquireResult == -4 /* VK_ERROR_DEVICE_LOST */) {
            fprintf(stderr, "vkAcquireNextImageKHR: VK_ERROR_DEVICE_LOST — triggering rebuild\n");
            sc->needsRebuild = 1;
        } else {
            fprintf(stderr, "vkAcquireNextImageKHR failed: %d\n", acquireResult);
        }
        return;
    }

    /* Use a finite timeout (2 seconds) to avoid infinite hangs when the
     * GPU is stuck or the swapchain is dead. A healthy frame completes
     * in <16ms; 2s gives plenty of headroom for OS scheduling. */
    VkResult fenceResult = vkWaitForFencesFn((VkDevice)device, 1, &sc->fences[imageIndex], VK_TRUE, 2000000000ULL /* 2s in ns */);
    if (fenceResult == VK_TIMEOUT) {
        fprintf(stderr, "vkWaitForFences: timeout (GPU may be hung)\n");
        sc->needsRebuild = 1;
        return;
    }
    vkResetFencesFn((VkDevice)device, 1, &sc->fences[imageIndex]);

    /* Inline screenshot staging buffer. Created BEFORE recording so the copy
     * can go into the frame's own command buffer; the image is app-owned
     * here (acquired, not yet presented), which makes the readback legal. */
    VkBuffer captureBuf = VK_NULL_HANDLE;
    VmaAllocation captureAlloc = VK_NULL_HANDLE;
    const uint32_t captureW = sc->extent.width;
    const uint32_t captureH = sc->extent.height;
    if (sc->captureRequested && captureW > 0 && captureH > 0) {
        const VkDeviceSize bufSize = (VkDeviceSize)captureW * captureH * 4;
        VkBufferCreateInfo capBci = {
            .sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO,
            .size = bufSize,
            .usage = VK_BUFFER_USAGE_TRANSFER_DST_BIT,
            .sharingMode = VK_SHARING_MODE_EXCLUSIVE
        };
        VmaAllocationCreateInfo capAllocInfo = {
            .usage = VMA_MEMORY_USAGE_AUTO,
            .flags = VMA_ALLOCATION_CREATE_HOST_ACCESS_RANDOM_BIT,
        };
        if (vmaCreateBuffer(g_vmaAllocator, &capBci, &capAllocInfo, &captureBuf, &captureAlloc, NULL) != VK_SUCCESS) {
            captureBuf = VK_NULL_HANDLE;
            captureAlloc = VK_NULL_HANDLE;
        }
    }

    VkCommandBuffer cb = sc->commandBuffers[imageIndex];
    vkResetCommandBufferFn(cb, 0);

    VkCommandBufferBeginInfo cbbi = {
        .sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO,
        .flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT
    };
    VkResult beginResult = vkBeginCommandBufferFn(cb, &cbbi);
    if (beginResult != VK_SUCCESS) {
        fprintf(stderr, "vkBeginCommandBuffer failed: %d\n", beginResult);
        return;
    }

    VkClearValue clearValues[2];
    /* Base sky blue; the gradient sky quad draws over it in the world pass. */
    clearValues[0].color = (VkClearColorValue){{ 0.35f, 0.60f, 0.90f, 1.0f }};
    clearValues[1].depthStencil = (VkClearDepthStencilValue){ 1.0f, 0 };
    VkRenderPassBeginInfo rpbi = {
        .sType = VK_STRUCTURE_TYPE_RENDER_PASS_BEGIN_INFO,
        .renderPass = sc->renderPass,
        .framebuffer = sc->framebuffers[imageIndex],
        .renderArea = { {0, 0}, sc->extent },
        .clearValueCount = 2,
        .pClearValues = clearValues
    };

    vkCmdBeginRenderPassFn(cb, &rpbi, VK_SUBPASS_CONTENTS_INLINE);

    VkViewport viewport = {
        .x = 0.0f, .y = 0.0f,
        .width = (float)sc->extent.width,
        .height = (float)sc->extent.height,
        .minDepth = 0.0f, .maxDepth = 1.0f
    };
    VkRect2D scissor = { {0, 0}, sc->extent };

    /* World geometry: depth-tested pipeline. Skipped while on the title
     * screen (no ranges yet). The pipeline is bound unconditionally when it
     * exists — the old code bound it inside the world-draw guard, so the
     * title screen issued a draw with NO bound pipeline -> segfault. */
    if (pl && pl->graphicsPipeline && pl->pipelineLayout) {
        vkCmdBindPipelineFn(cb, VK_PIPELINE_BIND_POINT_GRAPHICS, pl->graphicsPipeline);
        vkCmdSetViewportFn(cb, 0, 1, &viewport);
        vkCmdSetScissorFn(cb, 0, 1, &scissor);

        /* Push world uniforms (MVP + camera pos + time) to the vertex shader */
        float worldPush[20] = {0};
        if (worldPC) memcpy(worldPush, worldPC, 20 * sizeof(float));
        vkCmdPushConstantsFn(cb, pl->pipelineLayout, VK_SHADER_STAGE_VERTEX_BIT, 0, 80, worldPush);

        /* Opaque pass: one draw per VISIBLE chunk (frustum-culled on the
         * Kotlin side). vkCmdDraw's firstVertex picks the chunk's slice of
         * the shared world buffer — no buffer rebuild needed when looking
         * around. */
        if (ranges && rangeCount > 0 && pl->vertexBuffer) {
            VkDeviceSize offset = 0;
            vkCmdBindVertexBuffersFn(cb, 0, 1, &pl->vertexBuffer, &offset);
            for (uint32_t i = 0; i < rangeCount; i++) {
                uint32_t solidCount = ranges[i * 4 + 1];
                if (solidCount > 0) {
                    vkCmdDrawFn(cb, solidCount, 1, ranges[i * 4 + 0], 0);
                }
            }
        }

        /* Transparent water pass: drawn AFTER all solid geometry so it
         * alpha-blends over the complete opaque world. It writes depth, so
         * the sky quad drawn next stays occluded behind the water surface. */
        if (water && water->graphicsPipeline && water->pipelineLayout && water->waterBuffer && ranges && rangeCount > 0) {
            vkCmdBindPipelineFn(cb, VK_PIPELINE_BIND_POINT_GRAPHICS, water->graphicsPipeline);
            vkCmdPushConstantsFn(cb, water->pipelineLayout, VK_SHADER_STAGE_VERTEX_BIT, 0, 80, worldPush);
            VkDeviceSize woffset = 0;
            vkCmdBindVertexBuffersFn(cb, 0, 1, &water->waterBuffer, &woffset);
            for (uint32_t i = 0; i < rangeCount; i++) {
                uint32_t waterCount = ranges[i * 4 + 3];
                if (waterCount > 0) {
                    vkCmdDrawFn(cb, waterCount, 1, ranges[i * 4 + 2], 0);
                }
            }
        }

        /* Sky: fullscreen gradient quad drawn AFTER terrain. Its depth
         * (0.9999) is behind every terrain fragment (terrain writes smaller
         * depth values), so the LESS depth test only lets it fill the gaps
         * where nothing was drawn — the blue sky between/above the world.
         * Rebind the world pipeline first (the water pass may have bound its
         * own pipeline). */
        if (pl->skyVertexBuffer && pl->skyVertexCount > 0) {
            vkCmdBindPipelineFn(cb, VK_PIPELINE_BIND_POINT_GRAPHICS, pl->graphicsPipeline);
            float skyPush[20] = {0};
            skyPush[0] = 1.0f; skyPush[5] = 1.0f; skyPush[10] = 1.0f; skyPush[15] = 1.0f; /* identity MVP */
            vkCmdPushConstantsFn(cb, pl->pipelineLayout, VK_SHADER_STAGE_VERTEX_BIT, 0, 80, skyPush);

            VkDeviceSize skyOffset = 0;
            vkCmdBindVertexBuffersFn(cb, 0, 1, &pl->skyVertexBuffer, &skyOffset);
            vkCmdDrawFn(cb, pl->skyVertexCount, 1, 0, 0);
        }
    }

    /* UI overlay (title screen + HUD): its own depth-DISABLED pipeline so it
     * always draws on top of the world, regardless of the depth buffer.
     * (Before, overlay quads were emitted at z=0 -> depth 0.5 and culled by
     * the world pipeline's LESS depth test once earlier quads wrote 0.5 —
     * that's why the title text never appeared.) */
    if (hud && hud->graphicsPipeline && hud->pipelineLayout && hud->vertexBuffer && hud->vertexCount > 0) {
        vkCmdBindPipelineFn(cb, VK_PIPELINE_BIND_POINT_GRAPHICS, hud->graphicsPipeline);
        vkCmdSetViewportFn(cb, 0, 1, &viewport);
        vkCmdSetScissorFn(cb, 0, 1, &scissor);

        float hudPush[20] = {0};
        if (hudPC) memcpy(hudPush, hudPC, 16 * sizeof(float));
        vkCmdPushConstantsFn(cb, hud->pipelineLayout, VK_SHADER_STAGE_VERTEX_BIT, 0, 80, hudPush);

        VkDeviceSize hudOffset = 0;
        vkCmdBindVertexBuffersFn(cb, 0, 1, &hud->vertexBuffer, &hudOffset);
        vkCmdDrawFn(cb, hud->vertexCount, 1, 0, 0);
    }

    /* ── ImGui overlay ──
     * Render ImGui draw data inside the render pass, after the UI overlay
     * but before ending the render pass. The ImGui Vulkan backend requires
     * an active render pass and command buffer. */
    if (strata_imgui_has_draw_data()) {
        strata_imgui_render_to(cb);
    }

    vkCmdEndRenderPassFn(cb);

    /* The render pass leaves the image in COLOR_ATTACHMENT_OPTIMAL (its
     * finalLayout). Move it to PRESENT_SRC explicitly here — through the
     * inline readback when a screenshot is pending. PRESENT_SRC is never a
     * barrier SOURCE (see the render-pass finalLayout comment). */
    if (sc->captureRequested && captureBuf) {
        VkImageMemoryBarrier toTransfer = {
            .sType = VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER,
            .oldLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL,
            .newLayout = VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL,
            /* Explicit memory dependency: the copy must see the render pass's
             * color writes. Without it, Intel's tiled renderer (TBIMR) can
             * hang its copy engine waiting on a deferred tile flush. */
            .srcAccessMask = VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT,
            .dstAccessMask = VK_ACCESS_TRANSFER_READ_BIT,
            .srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED,
            .dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED,
            .image = sc->images[imageIndex],
            .subresourceRange = { VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1 }
        };
        vkCmdPipelineBarrierFn(cb, VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT,
            0, 0, NULL, 0, NULL, 1, &toTransfer);

        VkBufferImageCopy capRegion = {
            .bufferOffset = 0,
            .bufferRowLength = 0,
            .bufferImageHeight = 0,
            .imageSubresource = { VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1 },
            .imageOffset = { 0, 0, 0 },
            .imageExtent = { captureW, captureH, 1 }
        };
        vkCmdCopyImageToBufferFn(cb, sc->images[imageIndex], VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL, captureBuf, 1, &capRegion);

        VkImageMemoryBarrier toPresent = {
            .sType = VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER,
            .oldLayout = VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL,
            .newLayout = VK_IMAGE_LAYOUT_PRESENT_SRC_KHR,
            .srcAccessMask = VK_ACCESS_TRANSFER_WRITE_BIT,
            .dstAccessMask = 0,
            .srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED,
            .dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED,
            .image = sc->images[imageIndex],
            .subresourceRange = { VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1 }
        };
        vkCmdPipelineBarrierFn(cb, VK_PIPELINE_STAGE_TRANSFER_BIT, VK_PIPELINE_STAGE_BOTTOM_OF_PIPE_BIT,
            0, 0, NULL, 0, NULL, 1, &toPresent);
    } else {
        VkImageMemoryBarrier toPresent = {
            .sType = VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER,
            .oldLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL,
            .newLayout = VK_IMAGE_LAYOUT_PRESENT_SRC_KHR,
            /* Make the render pass's color writes visible to the present engine. */
            .srcAccessMask = VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT,
            .dstAccessMask = 0,
            .srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED,
            .dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED,
            .image = sc->images[imageIndex],
            .subresourceRange = { VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1 }
        };
        vkCmdPipelineBarrierFn(cb, VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT, VK_PIPELINE_STAGE_BOTTOM_OF_PIPE_BIT,
            0, 0, NULL, 0, NULL, 1, &toPresent);
    }

    vkEndCommandBufferFn(cb);

    VkPipelineStageFlags waitStages[] = { VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT };
    VkSubmitInfo submitInfo = {
        .sType = VK_STRUCTURE_TYPE_SUBMIT_INFO,
        .waitSemaphoreCount = 1,
        .pWaitSemaphores = &sc->imageAvailableSemaphores[ring],
        .pWaitDstStageMask = waitStages,
        .commandBufferCount = 1,
        .pCommandBuffers = &cb,
        .signalSemaphoreCount = 1,
        .pSignalSemaphores = &sc->renderFinishedSemaphores[ring]
    };
    VkResult submitResult = vkQueueSubmitFn((VkQueue)queue, 1, &submitInfo, sc->fences[imageIndex]);
    if (submitResult != VK_SUCCESS) {
        fprintf(stderr, "vkQueueSubmit failed: %d\n", submitResult);
    if (captureBuf) vmaDestroyBuffer(g_vmaAllocator, captureBuf, captureAlloc);
    sc->captureRequested = 0;
    sc->captureResult = 0;
    return;
    }

    /* Capture finalize: wait for the copy, write the BMP, clean up. The flag
     * is always cleared (even if staging creation failed earlier). */
    if (sc->captureRequested) {
        if (captureBuf) {
            if (vkQueueWaitIdleFn((VkQueue)queue) == VK_SUCCESS) {
                void *capData = NULL;
                const VkDeviceSize capSize = (VkDeviceSize)captureW * captureH * 4;
                if (vmaMapMemory(g_vmaAllocator, captureAlloc, &capData) == VK_SUCCESS && capData) {
                    strata_write_bmp(sc->capturePath, (const uint8_t *)capData, captureW, captureH);
                    vmaUnmapMemory(g_vmaAllocator, captureAlloc);
                    sc->captureResult = 1;
                }
            }
            vmaDestroyBuffer(g_vmaAllocator, captureBuf, captureAlloc);
        }
        sc->captureRequested = 0;
    }

    VkPresentInfoKHR presentInfo = {
        .sType = VK_STRUCTURE_TYPE_PRESENT_INFO_KHR,
        .waitSemaphoreCount = 1,
        .pWaitSemaphores = &sc->renderFinishedSemaphores[ring],
        .swapchainCount = 1,
        .pSwapchains = &sc->swapchain,
        .pImageIndices = &imageIndex
    };
    VkResult presentResult = vkQueuePresentFn((VkQueue)queue, &presentInfo);
    if (presentResult == VK_ERROR_OUT_OF_DATE_KHR || presentResult == VK_SUBOPTIMAL_KHR) {
        sc->needsRebuild = 1;
    } else if (presentResult != VK_SUCCESS) {
        fprintf(stderr, "vkQueuePresentKHR failed: %d\n", presentResult);
    } else {
        sc->lastImageIndex = imageIndex;
    }
    sc->frameIndex++;
}

/* ────────────────────────────────────────────────────────────
   Inline screenshot request helpers (host side)
   ──────────────────────────────────────────────────────────── */

static inline void strata_request_capture(StrataSwapchain *sc, const char *path) {
    if (!sc || !path) return;
    snprintf(sc->capturePath, sizeof(sc->capturePath), "%s", path);
    sc->captureRequested = 1;
    sc->captureResult = 0;
}

static inline uint32_t strata_capture_done(StrataSwapchain *sc) {
    return sc ? sc->captureResult : 0;
}

static inline void strata_capture_ack(StrataSwapchain *sc) {
    if (sc) sc->captureResult = 0;
}

/* ────────────────────────────────────────────────────────────
   Screenshot (F2): read back the last presented swapchain image
   into a host-visible staging buffer and write a 32-bit BMP.
   The swapchain format is B8G8R8A8, so BMP rows are stored
   bottom-up as B,G,R bytes (alpha dropped).
   ──────────────────────────────────────────────────────────── */

static inline void strata_write_bmp(const char *path, const uint8_t *pixels, uint32_t w, uint32_t h) {
    FILE *f = fopen(path, "wb");
    if (!f) return;
    uint32_t rowSize = w * 4;
    uint32_t dataSize = rowSize * h;
    uint32_t fileSize = 54 + dataSize;
    uint8_t header[54] = {0};
    header[0] = 'B'; header[1] = 'M';
    header[2] = fileSize & 0xFF; header[3] = (fileSize >> 8) & 0xFF;
    header[4] = (fileSize >> 16) & 0xFF; header[5] = (fileSize >> 24) & 0xFF;
    header[10] = 54;                 /* pixel data offset */
    header[14] = 40;                 /* DIB header size */
    header[18] = w & 0xFF; header[19] = (w >> 8) & 0xFF;
    header[20] = (w >> 16) & 0xFF; header[21] = (w >> 24) & 0xFF;
    header[22] = h & 0xFF; header[23] = (h >> 8) & 0xFF;
    header[24] = (h >> 16) & 0xFF; header[25] = (h >> 24) & 0xFF;
    header[26] = 1;                  /* planes */
    header[28] = 32;                 /* bits per pixel */
    fwrite(header, 1, 54, f);
    for (uint32_t y = 0; y < h; y++) {
        const uint8_t *row = pixels + (h - 1 - y) * rowSize;   /* bottom-up */
        fwrite(row, 1, rowSize, f);
    }
    fclose(f);
}


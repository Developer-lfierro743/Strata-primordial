static inline void strata_destroy_pipeline(void *instance, void *device, StrataPipeline *pl) {
    if (!pl) return;
    PFN_vkGetInstanceProcAddr vkGetProcAddr = (PFN_vkGetInstanceProcAddr)SDL_Vulkan_GetVkGetInstanceProcAddr();
    PFN_vkDeviceWaitIdle vkDeviceWaitIdleFn = (PFN_vkDeviceWaitIdle)vkGetProcAddr((VkInstance)instance, "vkDeviceWaitIdle");
    if (vkDeviceWaitIdleFn) vkDeviceWaitIdleFn((VkDevice)device);

    PFN_vkDestroyBuffer vkDestroyBufferFn = (PFN_vkDestroyBuffer)vkGetProcAddr((VkInstance)instance, "vkDestroyBuffer");
    PFN_vkFreeMemory vkFreeMemoryFn = (PFN_vkFreeMemory)vkGetProcAddr((VkInstance)instance, "vkFreeMemory");
    PFN_vkDestroyPipeline vkDestroyPipelineFn = (PFN_vkDestroyPipeline)vkGetProcAddr((VkInstance)instance, "vkDestroyPipeline");
    PFN_vkDestroyPipelineLayout vkDestroyPipelineLayoutFn = (PFN_vkDestroyPipelineLayout)vkGetProcAddr((VkInstance)instance, "vkDestroyPipelineLayout");
    PFN_vkDestroyShaderModule vkDestroyShaderModuleFn = (PFN_vkDestroyShaderModule)vkGetProcAddr((VkInstance)instance, "vkDestroyShaderModule");

    if (pl->vertexBuffer) vmaDestroyBuffer(g_vmaAllocator, pl->vertexBuffer, pl->vertexAllocation);
    if (pl->waterBuffer) vmaDestroyBuffer(g_vmaAllocator, pl->waterBuffer, pl->waterAllocation);
    if (pl->skyVertexBuffer) vmaDestroyBuffer(g_vmaAllocator, pl->skyVertexBuffer, pl->skyAllocation);
    if (pl->graphicsPipeline && vkDestroyPipelineFn) vkDestroyPipelineFn((VkDevice)device, pl->graphicsPipeline, NULL);
    if (pl->pipelineLayout && vkDestroyPipelineLayoutFn) vkDestroyPipelineLayoutFn((VkDevice)device, pl->pipelineLayout, NULL);
    if (pl->vertModule && vkDestroyShaderModuleFn) vkDestroyShaderModuleFn((VkDevice)device, pl->vertModule, NULL);
    if (pl->fragModule && vkDestroyShaderModuleFn) vkDestroyShaderModuleFn((VkDevice)device, pl->fragModule, NULL);

    free(pl);
}

static inline void strata_destroy_swapchain(void *instance, void *device, StrataSwapchain *sc) {
    if (!sc) return;
    PFN_vkGetInstanceProcAddr vkGetProcAddr = (PFN_vkGetInstanceProcAddr)SDL_Vulkan_GetVkGetInstanceProcAddr();
    PFN_vkDeviceWaitIdle vkDeviceWaitIdleFn = (PFN_vkDeviceWaitIdle)vkGetProcAddr((VkInstance)instance, "vkDeviceWaitIdle");
    PFN_vkDestroySwapchainKHR vkDestroySwapchainFn = (PFN_vkDestroySwapchainKHR)vkGetProcAddr((VkInstance)instance, "vkDestroySwapchainKHR");
    PFN_vkDestroyImageView vkDestroyImageViewFn = (PFN_vkDestroyImageView)vkGetProcAddr((VkInstance)instance, "vkDestroyImageView");
    PFN_vkDestroyRenderPass vkDestroyRenderPassFn = (PFN_vkDestroyRenderPass)vkGetProcAddr((VkInstance)instance, "vkDestroyRenderPass");
    PFN_vkDestroyFramebuffer vkDestroyFramebufferFn = (PFN_vkDestroyFramebuffer)vkGetProcAddr((VkInstance)instance, "vkDestroyFramebuffer");
    PFN_vkDestroyCommandPool vkDestroyCommandPoolFn = (PFN_vkDestroyCommandPool)vkGetProcAddr((VkInstance)instance, "vkDestroyCommandPool");
    PFN_vkDestroySemaphore vkDestroySemaphoreFn = (PFN_vkDestroySemaphore)vkGetProcAddr((VkInstance)instance, "vkDestroySemaphore");
    PFN_vkDestroyFence vkDestroyFenceFn = (PFN_vkDestroyFence)vkGetProcAddr((VkInstance)instance, "vkDestroyFence");

    if (vkDeviceWaitIdleFn) vkDeviceWaitIdleFn((VkDevice)device);

    for (uint32_t i = 0; i < sc->imageCount; i++) {
        if (vkDestroyFenceFn && sc->fences[i]) vkDestroyFenceFn((VkDevice)device, sc->fences[i], NULL);
        if (vkDestroyImageViewFn && sc->views[i]) vkDestroyImageViewFn((VkDevice)device, sc->views[i], NULL);
        if (vkDestroyFramebufferFn && sc->framebuffers[i]) vkDestroyFramebufferFn((VkDevice)device, sc->framebuffers[i], NULL);
    }
    if (vkDestroyCommandPoolFn && sc->commandPool) vkDestroyCommandPoolFn((VkDevice)device, sc->commandPool, NULL);
    if (vkDestroyRenderPassFn && sc->renderPass) vkDestroyRenderPassFn((VkDevice)device, sc->renderPass, NULL);
    for (uint32_t i = 0; i < 3; i++) {
        if (vkDestroySemaphoreFn && sc->imageAvailableSemaphores[i]) vkDestroySemaphoreFn((VkDevice)device, sc->imageAvailableSemaphores[i], NULL);
        if (vkDestroySemaphoreFn && sc->renderFinishedSemaphores[i]) vkDestroySemaphoreFn((VkDevice)device, sc->renderFinishedSemaphores[i], NULL);
    }
    if (vkDestroyImageViewFn && sc->depthImageView) vkDestroyImageViewFn((VkDevice)device, sc->depthImageView, NULL);
    if (sc->depthImage) vmaDestroyImage(g_vmaAllocator, sc->depthImage, sc->depthImageAllocation);
    if (vkDestroySwapchainFn && sc->swapchain) vkDestroySwapchainFn((VkDevice)device, sc->swapchain, NULL);
    free(sc);
}

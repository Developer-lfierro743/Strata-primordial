typedef struct {
    int eventType;
    int keySymbol;
    float mouseDx;
    float mouseDy;
    int mouseButton;
    int windowWidth;
    int windowHeight;
    char text[64];   /* UTF-8 text from SDL_EVENT_TEXT_INPUT (chat typing) */
} StrataInputEvent;

/* Capture scancodes (physical keys), not keycodes (layout-dependent SDLK_*).
 * Main.kt indexes keyState with SDL_SCANCODE_W/A/S/D (26/4/22/7).
 * event.key.key is the virtual key (e.g. 'w' == 119) and will never match. */
static inline bool strata_poll_input(StrataInputEvent *outEvent, SDL_Window *window) {
    SDL_Event event;
    if (SDL_PollEvent(&event)) {
        outEvent->eventType = (int)event.type;
        outEvent->mouseDx = 0.0f;
        outEvent->mouseDy = 0.0f;
        outEvent->mouseButton = 0;
        outEvent->keySymbol = 0;
        outEvent->windowWidth = 0;
        outEvent->windowHeight = 0;
        outEvent->text[0] = '\0';
        if (event.type == SDL_EVENT_QUIT) {
            return true;
        } else if (event.type == SDL_EVENT_KEY_DOWN || event.type == SDL_EVENT_KEY_UP) {
            outEvent->keySymbol = (int)event.key.scancode;
        } else if (event.type == SDL_EVENT_TEXT_INPUT) {
            /* Chat typing: the OS delivers the actual characters (shift-aware,
             * layout-aware) here instead of raw scancodes. */
            SDL_strlcpy(outEvent->text, event.text.text, sizeof(outEvent->text));
        } else if (event.type == SDL_EVENT_MOUSE_MOTION) {
            outEvent->mouseDx = event.motion.xrel;
            outEvent->mouseDy = event.motion.yrel;
        } else if (event.type == SDL_EVENT_MOUSE_BUTTON_DOWN) {
            outEvent->mouseButton = (int)event.button.button;
        } else if (event.type == SDL_EVENT_WINDOW_RESIZED) {
            SDL_GetWindowSize(window, &outEvent->windowWidth, &outEvent->windowHeight);
        }
        return true;
    }
    return false;
}


/* ────────────────────────────────────────────────────────────
   Memory Type Helper (kept for fallback / non-VMA paths)
   ──────────────────────────────────────────────────────────── */

static inline uint32_t strata_find_memory_type(void *instance, void *physDevice, uint32_t typeFilter, uint32_t propertyFlags) {
    PFN_vkGetInstanceProcAddr vkGetProcAddr = (PFN_vkGetInstanceProcAddr)SDL_Vulkan_GetVkGetInstanceProcAddr();
    PFN_vkGetPhysicalDeviceMemoryProperties vkGetPhysicalDeviceMemoryPropertiesFn =
        (PFN_vkGetPhysicalDeviceMemoryProperties)vkGetProcAddr((VkInstance)instance, "vkGetPhysicalDeviceMemoryProperties");
    if (!vkGetPhysicalDeviceMemoryPropertiesFn) return UINT32_MAX;

    VkPhysicalDeviceMemoryProperties memProps;
    vkGetPhysicalDeviceMemoryPropertiesFn((VkPhysicalDevice)physDevice, &memProps);

    for (uint32_t i = 0; i < memProps.memoryTypeCount; i++) {
        if ((typeFilter & (1u << i)) && (memProps.memoryTypes[i].propertyFlags & propertyFlags) == propertyFlags) {
            return i;
        }
    }
    return UINT32_MAX;
}

/* ────────────────────────────────────────────────────────────
   Swapchain
   ──────────────────────────────────────────────────────────── */

typedef struct {
    VkSwapchainKHR swapchain;
    VkFormat format;
    VkExtent2D extent;
    uint32_t imageCount;
    VkImage images[8];
    VkImageView views[8];
    VkImage depthImage;
    VmaAllocation depthImageAllocation;
    VkImageView depthImageView;
    VkRenderPass renderPass;
    VkFramebuffer framebuffers[8];
    VkCommandPool commandPool;
    VkCommandBuffer commandBuffers[8];
    VkFence fences[8];
    /* Per-frame semaphore ring: with a multi-image swapchain several frames
     * are in flight, so a single semaphore pair would be re-signaled while a
     * signal is still pending — undefined behavior that can hang strict
     * drivers (Intel). One pair per in-flight slot is the canonical pattern. */
    VkSemaphore imageAvailableSemaphores[3];
    VkSemaphore renderFinishedSemaphores[3];
    uint32_t frameIndex;   /* ring cursor, advanced every rendered frame */
    uint32_t lastImageIndex;
    /* Inline screenshot request. The host sets captureRequested + capturePath;
     * render_frame reads back the CURRENT frame's app-owned image (reading a
     * presented image is a spec violation that hangs Intel's display engine),
     * writes the BMP and stores the result in captureResult. */
    uint32_t captureRequested;
    uint32_t captureResult;
    char capturePath[256];
    /* Set to 1 by render_frame when VK_ERROR_OUT_OF_DATE_KHR or
     * VK_ERROR_SUBOPTIMAL_KHR is returned by vkAcquireNextImageKHR or
     * vkQueuePresentKHR. The host must destroy and recreate the swapchain.
     * Common on Intel Xe iGPUs during resize, minimize, or TDR recovery. */
    uint32_t needsRebuild;
} StrataSwapchain;

